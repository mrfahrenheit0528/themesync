"""
ThemeSync — Detector accuracy as mean IoU (Phase 1; manuscript p.62)
=====================================================================
p.62: IoU "calculated the area of overlap between the predicted bounding
boxes generated by the YOLOv8 object detection model and the ground-truth
annotations established in the empirical master-layout dataset's held-out
validation split (40 images)". This script measures exactly that for the
deployed detector. It only reads: no model, label, pipeline or Phase 4 file
changes.

  Detections   the deployed operating point, as LayoutExtractor runs it:
               the checkpoint's training image size, kept at confidence
               >= 0.25, or >= 0.15 for title-sized text (constants
               imported from layout_extractor.py)
  Ground truth the validation labels as training saw them
               (prepare_master_layout_dataset.to_box): polygon rows become
               their enclosing boxes; boxes over half the image are dropped
  Pairing      per image and class, one-to-one, the pairing that maximises
               the total IoU (Hungarian algorithm)
  Measures     strict mean IoU: over every ground-truth box, a box with no
                 overlapping detection counting as 0
               found (IoU >= 0.5, the usual threshold, as in mAP50): how
                 many boxes were found (recall), how many detections were
                 right (precision), and their mean IoU
               each per class and pooled over all boxes

Reported for all 40 validation images (the manuscript's set) and without
any that duplicate a training image (poster_overlap's near-duplicate
rule; notes §3.30 found HIRAYA in both splits).

Usage:
  python src/evaluation/yolo_iou.py
  python src/evaluation/yolo_iou.py --weights themesync_yolo_v5.pt --out results/yolo_iou.json
"""

import argparse
import datetime
import glob
import json
import os
import platform
import sys

import numpy as np
from scipy.optimize import linear_sum_assignment

_EVAL_DIR = os.path.dirname(os.path.abspath(__file__))
_SRC = os.path.dirname(_EVAL_DIR)
_ROOT = os.path.dirname(_SRC)
for _p in (_EVAL_DIR, os.path.join(_SRC, "data_preprocessing")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import poster_overlap                                                         # noqa: E402
from layout_extractor import DEFAULT_CONFIDENCE, TITLE_CONFIDENCE, TITLE_MIN_AREA  # noqa: E402
from prepare_master_layout_dataset import to_box                             # noqa: E402

BATCH = os.path.join(_ROOT, "data", "raw", "master_layout_batch")
FOUND_IOU = 0.5
MAX_AREA = 0.5
CLASSES = ("logo", "text", "underlay", "embellishment")


def iou(a, b) -> float:
    """IoU of two (x1, y1, x2, y2) boxes."""
    w = min(a[2], b[2]) - max(a[0], b[0])
    h = min(a[3], b[3]) - max(a[1], b[1])
    if w <= 0 or h <= 0:
        return 0.0
    inter = w * h
    return inter / ((a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter)


def ground_truth(label_path: str, names: list, img_w: int, img_h: int) -> list:
    """[(class, (x1, y1, x2, y2))] in pixels, cleaned as for training."""
    boxes = []
    if not os.path.exists(label_path):
        return boxes
    with open(label_path) as f:
        for line in f:
            parts = line.split()
            if len(parts) < 5:
                continue
            cid, cx, cy, w, h = to_box(parts)
            if w <= 0 or h <= 0 or w * h > MAX_AREA:
                continue
            boxes.append((names[cid], ((cx - w / 2) * img_w, (cy - h / 2) * img_h,
                                       (cx + w / 2) * img_w, (cy + h / 2) * img_h)))
    return boxes


def detections(model, image_path: str, imgsz: int) -> tuple:
    """The deployed operating point (LayoutExtractor.extract's filter).
    Returns ([(class, box, confidence)], (width, height))."""
    result = model.predict(image_path, conf=min(DEFAULT_CONFIDENCE, TITLE_CONFIDENCE), imgsz=imgsz,
                           verbose=False)[0]
    img_h, img_w = result.orig_shape
    out = []
    for box in result.boxes:
        name = model.names[int(box.cls.item())]
        x1, y1, x2, y2 = [float(v) for v in box.xyxy[0].tolist()]
        conf = float(box.conf.item())
        title_sized = name == "text" and (x2 - x1) * (y2 - y1) >= TITLE_MIN_AREA * img_w * img_h
        if conf < DEFAULT_CONFIDENCE and not title_sized:
            continue
        out.append((name, (x1, y1, x2, y2), conf))
    return out, (img_w, img_h)


def pair(gts: list, preds: list) -> list:
    """Per class, one-to-one pairs maximising the total IoU. Returns
    [(class, iou of the gt box with its detection, or 0 if none)] per gt
    box, and the number of detections per class."""
    rows = []
    for cls in CLASSES:
        g = [b for c, b in gts if c == cls]
        p = [b for c, b, _ in preds if c == cls]
        if not g:
            continue
        best = [0.0] * len(g)
        if p:
            m = np.array([[iou(a, b) for b in p] for a in g])
            for i, j in zip(*linear_sum_assignment(-m)):
                best[i] = float(m[i, j])
        rows += [(cls, v) for v in best]
    return rows


def summarise(gt_rows: list, n_pred: dict) -> dict:
    """Strict and found figures, per class and pooled."""
    def block(values: list, n_detections: int) -> dict:
        found = [v for v in values if v >= FOUND_IOU]
        return {
            "ground_truth_boxes": len(values),
            "detections": n_detections,
            "strict_mean_iou": round(float(np.mean(values)), 4) if values else None,
            "strict_sd": round(float(np.std(values, ddof=1)), 4) if len(values) > 1 else None,
            "found": len(found),
            "recall": round(len(found) / len(values), 4) if values else None,
            "precision": round(len(found) / n_detections, 4) if n_detections else None,
            "found_mean_iou": round(float(np.mean(found)), 4) if found else None,
            "found_sd": round(float(np.std(found, ddof=1)), 4) if len(found) > 1 else None,
        }
    out = {cls: block([v for c, v in gt_rows if c == cls], n_pred.get(cls, 0)) for cls in CLASSES}
    out["all"] = block([v for _, v in gt_rows], sum(n_pred.values()))
    return out


def main():
    parser = argparse.ArgumentParser(description="Mean IoU of the deployed detector on the validation split")
    parser.add_argument("--weights", default=os.path.join(_ROOT, "themesync_yolo_v5.pt"))
    parser.add_argument("--data", default=BATCH, help="the Roboflow export (data.yaml, valid/images, valid/labels)")
    parser.add_argument("--version", default="v5", help="checkpoint version, for its training images")
    parser.add_argument("--out", default=os.path.join(_ROOT, "results", "yolo_iou.json"))
    args = parser.parse_args()

    import torch
    import ultralytics
    import yaml
    from ultralytics import YOLO

    with open(os.path.join(args.data, "data.yaml")) as f:
        names = yaml.safe_load(f)["names"]
    names = [names[k] for k in sorted(names)] if isinstance(names, dict) else list(names)
    model = YOLO(args.weights)
    imgsz = int((getattr(model, "ckpt", None) or {}).get("train_args", {}).get("imgsz", 640))
    train_imgs = poster_overlap.training_images(args.version)

    images = sorted(glob.glob(os.path.join(args.data, "valid", "images", "*")))
    per_image, all_rows, clean_rows = [], [], []
    n_all, n_clean = {}, {}
    for path in images:
        stem = os.path.splitext(os.path.basename(path))[0]
        preds, (w, h) = detections(model, path, imgsz)
        gts = ground_truth(os.path.join(args.data, "valid", "labels", stem + ".txt"), names, w, h)
        rows = pair(gts, preds)
        dup = poster_overlap.find_match(path, train_imgs) if train_imgs else None
        counts = {}
        for c, _, _ in preds:
            counts[c] = counts.get(c, 0) + 1
        all_rows += rows
        for c, k in counts.items():
            n_all[c] = n_all.get(c, 0) + k
        if not dup:
            clean_rows += rows
            for c, k in counts.items():
                n_clean[c] = n_clean.get(c, 0) + k
        per_image.append({"image": os.path.basename(path), "duplicates_training_image": dup,
                          "ground_truth_boxes": len(gts), "detections": len(preds),
                          "strict_mean_iou": round(float(np.mean([v for _, v in rows])), 4) if rows else None})

    dups = [r["image"] for r in per_image if r["duplicates_training_image"]]
    report = {
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "weights": os.path.basename(args.weights),
        "settings": {
            "image_size": imgsz,
            "confidence": DEFAULT_CONFIDENCE,
            "title_text_confidence": TITLE_CONFIDENCE,
            "title_min_area": TITLE_MIN_AREA,
            "ground_truth": "validation labels; polygons -> enclosing boxes; boxes over half the image dropped",
            "pairing": "per image and class, one-to-one, maximising the total IoU (Hungarian algorithm)",
            "strict_mean_iou": "mean over every ground-truth box; a box with no overlapping detection counts 0",
            "found": f"a pair with IoU >= {FOUND_IOU}; recall = found / ground-truth boxes, "
                     "precision = found / detections, found_mean_iou = mean IoU of those pairs",
        },
        "environment": {"python": platform.python_version(), "torch": torch.__version__,
                        "ultralytics": ultralytics.__version__,
                        "device": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "cpu"},
        "validation_images": len(images),
        "duplicates_of_training_images": dups,
        "results": {
            f"all {len(images)} validation images": summarise(all_rows, n_all),
            f"{len(images) - len(dups)} without training duplicates": summarise(clean_rows, n_clean),
        },
        "per_image": per_image,
    }
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    print(f"{report['weights']} at {imgsz} px, confidence {DEFAULT_CONFIDENCE} "
          f"(title text {TITLE_CONFIDENCE}); {len(images)} validation images")
    print(f"Duplicates of training images: {', '.join(dups) or 'none'}")
    for subset, res in report["results"].items():
        print(f"\n{subset}")
        print(f"  {'class':<14}{'boxes':>6}{'dets':>6}{'strict mIoU':>13}{'recall':>8}{'precision':>11}{'found mIoU':>12}")
        for cls in (*CLASSES, "all"):
            r = res[cls]
            fmt = lambda v: "-" if v is None else f"{v:.3f}"
            print(f"  {cls:<14}{r['ground_truth_boxes']:>6}{r['detections']:>6}{fmt(r['strict_mean_iou']):>13}"
                  f"{fmt(r['recall']):>8}{fmt(r['precision']):>11}{fmt(r['found_mean_iou']):>12}")
    print(f"\n-> {os.path.relpath(args.out, _ROOT)}")


if __name__ == "__main__":
    main()
